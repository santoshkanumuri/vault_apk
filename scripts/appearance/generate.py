"""Writes every platform file from the shared palette.

    python scripts/appearance/design.py  scripts/appearance/nuvori-appearance-v1.json   # only to change the palette
    python scripts/appearance/check.py   scripts/appearance/nuvori-appearance-v1.json   # contrast gate, must pass
    python scripts/appearance/generate.py [path/to/card_app_windows]

The JSON file is the single source of truth. It is copied byte-for-byte into the Windows repository, and the
tests on both sides compare the generated files with it. Never edit a generated file by hand.
"""
import json
import pathlib
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent
ANDROID = HERE.parent.parent
PALETTE = HERE / "nuvori-appearance-v1.json"
HEADER = "GENERATED by scripts/appearance/generate.py from nuvori-appearance-v1.json. Do not edit."

ACCENT_KEYS = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer"]
SURFACE_KEYS = ["background", "containerLow", "container", "containerHigh", "containerHighest", "hover", "text", "muted",
                "subtle", "outline", "hairline", "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
                "tertiary"]
# Windows app CSS variables. Status colors stay fixed: green means success on every theme.
WINDOWS_ACCENT = {"--primary": "primary", "--on-primary": "onPrimary", "--primary-container": "primaryContainer",
                  "--on-primary-container": "onPrimaryContainer", "--focus": "primary"}
WINDOWS_SURFACE = {"--bg": "background", "--surface": "container", "--surface-2": "containerHighest", "--hover": "hover",
                   "--text": "text", "--muted": "muted", "--subtle": "subtle", "--outline": "outline", "--hairline": "hairline"}


def kotlin_color(value):
    return "0xFF" + value.lstrip("#").upper()


def kotlin(p):
    def tones(cls, keys, values):
        return f"{cls}(" + ", ".join(kotlin_color(values[k]) for k in keys) + ")"
    lines = [f"// {HEADER}", "package com.privatevault.app.appearance", "",
             "/** Colors as ARGB. Same order as the constructor of each class. */",
             "data class AccentTones(val primary: Long, val onPrimary: Long, val primaryContainer: Long, val onPrimaryContainer: Long)",
             "",
             "data class SurfaceTones(val background: Long, val containerLow: Long, val container: Long, val containerHigh: Long,",
             "    val containerHighest: Long, val hover: Long, val text: Long, val muted: Long, val subtle: Long, val outline: Long,",
             "    val hairline: Long, val secondary: Long, val onSecondary: Long, val secondaryContainer: Long,",
             "    val onSecondaryContainer: Long, val tertiary: Long)",
             "",
             "data class AppearanceAccent(val id: String, val name: String, val swatch: Long, val dark: AccentTones, val light: AccentTones)",
             "",
             "data class AppearanceSurface(val id: String, val name: String, val swatch: Long, val dark: SurfaceTones, val light: SurfaceTones)",
             "",
             "object AppearancePalette {",
             f"    const val VERSION = {p['version']}",
             f"    const val DEFAULT_ACCENT = \"{p['defaults']['accent']}\"",
             f"    const val DEFAULT_SURFACE = \"{p['defaults']['surface']}\"",
             "",
             "    val accents: List<AppearanceAccent> = listOf("]
    for a in p["accents"]:
        lines.append(f"        AppearanceAccent(\"{a['id']}\", \"{a['name']}\", {kotlin_color(a['swatch'])},")
        lines.append(f"            {tones('AccentTones', ACCENT_KEYS, a['dark'])},")
        lines.append(f"            {tones('AccentTones', ACCENT_KEYS, a['light'])}),")
    lines += ["    )", "", "    val surfaces: List<AppearanceSurface> = listOf("]
    for s in p["surfaces"]:
        lines.append(f"        AppearanceSurface(\"{s['id']}\", \"{s['name']}\", {kotlin_color(s['swatch'])},")
        lines.append(f"            {tones('SurfaceTones', SURFACE_KEYS, s['dark'])},")
        lines.append(f"            {tones('SurfaceTones', SURFACE_KEYS, s['light'])}),")
    lines += ["    )", "",
              "    /** An unknown id (a newer palette on another device) falls back to the default, never to an error. */",
              "    fun accent(id: String?): AppearanceAccent = accents.firstOrNull { it.id == id } ?: accents.first { it.id == DEFAULT_ACCENT }",
              "",
              "    fun surface(id: String?): AppearanceSurface = surfaces.firstOrNull { it.id == id } ?: surfaces.first { it.id == DEFAULT_SURFACE }",
              "}", ""]
    return "\n".join(lines)


def windows_css(p):
    out = [f"/* {HEADER}", " * Accent and background blocks override the green defaults in styles.css. <html> carries",
           " * data-theme (light|dark, always resolved), data-accent and data-surface. */", ""]
    for kind, items, mapping in (("accent", p["accents"], WINDOWS_ACCENT), ("surface", p["surfaces"], WINDOWS_SURFACE)):
        for item in items:
            for mode in ("dark", "light"):
                body = " ".join(f"{var}: {item[mode][key]};" for var, key in mapping.items())
                out.append(f':root[data-theme="{mode}"][data-{kind}="{item["id"]}"] {{ {body} }}')
        out.append("")
    return "\n".join(out)


def extension_js(p):
    data = {"version": p["version"], "defaults": p["defaults"],
            "accents": {a["id"]: {"name": a["name"], "swatch": a["swatch"], "dark": a["dark"], "light": a["light"]} for a in p["accents"]},
            "surfaces": {s["id"]: {"name": s["name"], "swatch": s["swatch"], "dark": s["dark"], "light": s["light"]} for s in p["surfaces"]}}
    return (f"// {HEADER}\n// Loaded by the popup and the content scripts; exposes globalThis.NuvoriAppearancePalette.\n"
            f"globalThis.NuvoriAppearancePalette = Object.freeze({json.dumps(data, indent=2)});\n")


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path)


def main():
    p = json.loads(PALETTE.read_text(encoding="utf-8"))
    write(ANDROID / "watchcommon/src/main/kotlin/com/privatevault/app/appearance/AppearancePalette.kt", kotlin(p))
    test_copy = ANDROID / "watchcommon/src/test/resources/appearance/nuvori-appearance-v1.json"
    test_copy.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(PALETTE, test_copy)
    print("wrote", test_copy)
    if len(sys.argv) > 1:
        windows = pathlib.Path(sys.argv[1]).resolve()
        shutil.copyfile(PALETTE, windows / "src/appearance/nuvori-appearance-v1.json") if (windows / "src/appearance").is_dir() else (
            (windows / "src/appearance").mkdir(parents=True), shutil.copyfile(PALETTE, windows / "src/appearance/nuvori-appearance-v1.json"))
        print("wrote", windows / "src/appearance/nuvori-appearance-v1.json")
        write(windows / "src/appearance/palette.css", windows_css(p))
        write(windows / "extension/appearance-palette.js", extension_js(p))
        if (windows / "landing").is_dir():
            write(windows / "landing/palette.js", extension_js(p))


if __name__ == "__main__":
    main()
